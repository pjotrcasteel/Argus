#!/usr/bin/env python3
"""Build an independent GitHub Pages web annotator from a previously captured ARGUS Actions artifact.

Never uses WyrmForge internals, hidden game data, player predictions or autogenerated human labels.
Only deliberately chosen DEVELOPMENT frames are published. Held-out game frames stay unpublished.
"""
import argparse
import json
import struct
from pathlib import Path
from zipfile import ZipFile

RUN = "run-02"
SEED = "argus-m2-4-first-blind-research"
MAX_IMAGE_BYTES = 2_000_000
PNG_MAGIC = b"\x89PNG\r\n\x1a\n"


def build(archive: Path, destination: Path) -> None:
    with ZipFile(archive) as z:
        plan = json.loads(z.read("study-plan.json"))
        if plan.get("seed") != SEED:
            raise ValueError("Unexpected research sample seed.")
        matching = [a for a in plan["assignments"] if a["runId"] == RUN]
        if len(matching) != 1 or matching[0]["partition"] != "development":
            raise ValueError("Only the fixed development run can be published.")
        steps = matching[0]["frameSteps"]
        if len(steps) != 12 or len(set(steps)) != 12:
            raise ValueError("Exactly twelve previously selected original screenshot steps are required.")

        labels = json.loads(z.read(f"{RUN}/blind-labels.template.json"))
        if labels.get("runId") != RUN or labels.get("schemaVersion") != 1:
            raise ValueError("Invalid original label schema.")
        if [x["step"] for x in labels["frames"]] != steps:
            raise ValueError("Annotation template must use exactly the frozen sampled frames.")
        for item in labels["frames"]:
            if item["player"] != {"state": "unknown", "center": None} or item["threats"] != {
                "state": "unknown", "centers": None
            }:
                raise ValueError("The website must never pre-fill ARGUS guesses as human reference labels.")

        target = destination / "annoteren" / "run-02"
        target.mkdir(parents=True, exist_ok=True)
        frames = []
        for step in steps:
            filename = f"frame-{step:04}.png"
            raw = z.read(f"{RUN}/{filename}")
            if not 24 <= len(raw) <= MAX_IMAGE_BYTES or raw[:8] != PNG_MAGIC:
                raise ValueError("Missing/invalid/oversized source PNG.")
            width, height = struct.unpack(">II", raw[16:24])
            if (width, height) != (390, 844):
                raise ValueError(f"Unexpected source screenshot size for {filename}.")
            (target / filename).write_bytes(raw)
            frames.append({"step": step, "width": width, "height": height, "file": filename})

    template = Path(__file__).with_name("index.template.html").read_text(encoding="utf-8")
    if template.count("/*ARGUS_FRAMES*/") != 1 or template.count("/*ARGUS_LABELS*/") != 1:
        raise ValueError("Unsafe/missing template placeholders.")

    # Script closing tags cannot be smuggled into inline JSON.
    serialize = lambda value: json.dumps(value, ensure_ascii=False, separators=(",", ":")).replace("<", "\\u003c")
    page = template.replace("/*ARGUS_FRAMES*/", serialize(frames)).replace("/*ARGUS_LABELS*/", serialize(labels))
    (target / "index.html").write_text(page, encoding="utf-8")
    (destination / ".nojekyll").write_text("", encoding="utf-8")
    (destination / "index.html").write_text(
        '<!doctype html><html lang="nl"><meta charset="utf-8"><meta name="viewport" '
        'content="width=device-width,initial-scale=1"><title>ARGUS Annoteren</title>'
        '<body style="font:18px system-ui;max-width:680px;margin:40px auto;padding:20px">'
        '<h1>ARGUS — Beelden beoordelen</h1><p>Mobiel, zonder ZIP en zonder betaalde diensten.</p>'
        '<a href="annoteren/run-02/">Open de 12 screenshots van de ontwikkelrun →</a></body></html>',
        encoding="utf-8",
    )
    print(f"Prepared actual development run website, {len(frames)} verified screenshots, at {target}.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--archive", type=Path, required=True)
    parser.add_argument("--destination", type=Path, required=True)
    arguments = parser.parse_args()
    build(arguments.archive, arguments.destination)
